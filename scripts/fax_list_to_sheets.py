def generate_sql_from_fax() -> str:
    lines = [
        "-- FAX番号登録 / contact_method = 'fax'",
        "",
    ]
    for pref, name, fax, stype in FAX_DATA:
        n = name.replace("'", "''")
        f = fax.replace("'", "''")
        lines.append(
            f"UPDATE school_mailing_list SET fax_number = '{f}', contact_method = 'fax' "
            f"WHERE school_name = '{n}';"
        )
    return "\n".join(lines)


def to_csv() -> str:
    """スプレッドシートに貼り付けられる CSV を生成"""
    rows = [["都道府県", "学校名", "種別", "FAX番号", "送信状況", "備考"]]
    for pref, name, fax, stype in FAX_DATA:
        rows.append([pref, name, stype, fax, "未送信", ""])
    lines = []
    for row in rows:
        lines.append(",".join(f'"{c}"' for c in row))
    return "\n".join(lines)


def main():
    out_dir = Path(__file__).parent

    # SQL 出力
    sql_path = out_dir / "fax_update.sql"
    with open(sql_path, "w", encoding="utf-8") as f:
        f.write(generate_sql_from_fax())
    print(f"SQL 出力: {sql_path}  （{len(FAX_DATA)} 件）")

    # CSV 出力
    csv_path = out_dir / "fax_list.csv"
    with open(csv_path, "w", encoding="utf-8-sig") as f:
        f.write(to_csv())
    print(f"CSV 出力: {csv_path}")
    print()
    print("次のステップ:")
    print("  1. fax_list.csv を Google スプレッドシートにインポート")
    print("  2. 「送信状況」列を手動更新しながら FAX 送信")
    print("  3. fax_update.sql を Supabase SQL Editor で実行")


if __name__ == "__main__":
    main()
