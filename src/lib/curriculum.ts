// 算数・数学の隣接学年をまたぐ場合の科目解決
export function resolveSubject(subject: string, grade: string): string {
  if (subject === "数学" && grade.startsWith("小")) return "算数";
  if (subject === "算数" && !grade.startsWith("小")) return "数学";
  return subject;
}

export function getUnitsForGrade(subject: string, grade: string): Unit[] {
  const resolved = resolveSubject(subject, grade);
  return CURRICULUM[resolved]?.[grade] ?? [];
}

