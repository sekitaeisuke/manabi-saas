export type Unit = { name: string; semester?: 1 | 2 | 3 };

export const GRADE_ORDER = [
  "小1","小2","小3","小4","小5","小6",
  "中1","中2","中3",
  "高1","高2","高3",
];

export function getAdjacentGrades(grade: string): string[] {
  const idx = GRADE_ORDER.indexOf(grade);
  if (idx === -1) return [grade];
  const result: string[] = [];
  if (idx > 0) result.push(GRADE_ORDER[idx - 1]);
  result.push(grade);
  if (idx < GRADE_ORDER.length - 1) result.push(GRADE_ORDER[idx + 1]);
  return result;
}

